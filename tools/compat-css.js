// Builds css/compat.css: fallbacks for older Safari, used only when the browser lacks a feature.
//  .nogap   → flex layouts get margins instead of `gap` (Safari before 14.1)
//  .noclamp → clamp(min, ideal, max) becomes its max value (Safari before 13.1)
const fs = require('fs');
const css = fs.readFileSync(__dirname + '/../css/app.css', 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
const out = ['/* Generated by tools/compat-css.js from app.css. Do not edit. */'];
const clampMax = v => v.replace(/clamp\(([^(),]+|[^(),]*\([^()]*\)[^(),]*),\s*([^(),]+|[^(),]*\([^()]*\)[^(),]*),\s*([^(),]+|[^(),]*\([^()]*\)[^(),]*)\)/g, (_, a, b, c) => c.trim());
const pre = s => s.split(',').map(x => x.trim()).filter(Boolean);
// Walk rules, remembering @media wrappers.
const re = /(@media[^{]+)\{|([^{}@]+)\{([^{}]*)\}|\}/g; let m, media = null;
while ((m = re.exec(css))) {
  if (m[1]) { media = m[1].trim(); continue; }
  if (!m[2]) { media = null; continue; }
  const sel = m[2].trim(), body = m[3], wrap = r => media ? `${media}{${r}}` : r;
  if (/display:\s*(inline-)?flex/.test(body)) {
    const g = /(?:^|;)\s*gap:\s*([^;]+)/.exec(body);
    if (g) { const v = clampMax(g[1].trim()).split(/\s+/)[0]; out.push(wrap(`${pre(sel).map(s => `.nogap ${s}>*`).join(',')}{margin:calc(${v} / 2)}`)); }
  }
  const decls = body.split(';').filter(d => d.includes('clamp('));
  if (decls.length) out.push(wrap(`${pre(sel).map(s => s.startsWith(':root') ? '.noclamp' : `.noclamp ${s}`).join(',')}{${decls.map(d => clampMax(d.trim())).join(';')}}`));
}
// .noar → aspect-ratio (Safari 15+): give the element a height worked out from its width.
const re2 = /([^{}@]+)\{([^{}]*)\}/g; let r2;
while ((r2 = re2.exec(css))) {
  const sel = r2[1].trim(), body = r2[2], ar = /(?:^|;)\s*aspect-ratio:\s*([\d.]+)(?:\s*\/\s*([\d.]+))?/.exec(body), w = /(?:^|;)\s*width:\s*([^;]+)/.exec(body);
  if (!ar || !w || w[1].includes('%')) continue;
  const k = `${ar[2] || 1} / ${ar[1]}`, list = pre(sel);
  out.push(`${list.map(x => `.noar ${x}`).join(',')}{height:calc(${w[1].trim()} * ${k})}`);
  if (w[1].includes('clamp(')) out.push(`${list.map(x => `.noar.noclamp ${x}`).join(',')}{height:calc(${clampMax(w[1].trim())} * ${k})}`);
}
// Elements sized by their container: hand-made fallbacks.
out.push('.noar .board{height:min(100vw - 32px,420px)}', '.noar .pond .lily{height:calc(min(56vw,360px) / 3)}', '.noar .hrow b{min-height:2.2em}',
  '.noar .bslot{position:relative;height:0;padding-bottom:100%}', '.noar .bin-in .sitem{height:52px}', '.noar .bslot>svg{position:absolute;top:0;left:0}', '.noar .bub{height:72px}');
fs.writeFileSync(__dirname + '/../css/compat.css', out.join('\n') + '\n');
console.log(`css/compat.css: ${out.length - 1} rules`);
